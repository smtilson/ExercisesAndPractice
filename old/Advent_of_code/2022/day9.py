class Point():
    def __init__(self, x=0, y=0) -> None:
        self.x = x
        self.y = y

    def distance(self, other) -> float:
        return hypot(self.x-other.x, self.y-other.y)

    def move(self, direction: str) -> None:
        if direction == "U":
            self.y += 1
        elif direction == "D":
            self.y -= 1
        elif direction == "R":
            self.x += 1
        elif direction == "L":
            self.x -= 1
        else:
            raise ValueError("Input must be U,D,L, or R.")

    def display(self):
        return (self.x, self.y)


