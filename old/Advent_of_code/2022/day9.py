def process_data(raw_data: str) -> List[Tuple[Union[str, int]]]:
    data = raw_data.split("\n")
    data = [term.strip() for term in data]
    data = [term.split(' ') for term in data]
    data = [(term[0], int(term[1])) for term in data]
    return data


