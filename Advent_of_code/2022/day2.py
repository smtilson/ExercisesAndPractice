def determine_result(game: Tuple[str], rolls: dict) -> str:
    elf = game[0]
    me = game[1]
    if rolls[elf]["defeated_by"]==me:
        return "me"
    elif rolls[elf]["defeats"]==me:
        return "elf"
    else:
        return "draw"

def determine_roll(game: Tuple[str], rolls: dict) -> str:
    desired_result = ""
    roll = ""
    outcome = game[1]
    if outcome == "X":
        desired_result = "defeats"
    elif outcome == "Y":
        desired_result = "draw"
    elif outcome == "Z":
        desired_result = "defeated_by"
    if desired_result == "draw":
        roll = game[0]
    else:
        roll = rolls[game[0]][desired_result]
    return roll

def determine_score1(game: Tuple[str], rolls) -> int:
    score = 0
    if game[1]=="X":
        score += 1
    elif game[1] == "Y":
        score += 2
    elif game[1]=="Z":
        score += 3
    result = determine_result(game, rolls)
    if result == "me":
        score += 6
    elif result == "draw":
        score += 3
    return score

def determine_score2(game: Tuple[str], rolls) -> int:
    score = 0
    if game[1]=="X":
        score += 0
    elif game[1] == "Y":
        score += 3
    elif game[1]=="Z":
        score += 6
    roll = determine_roll(game, rolls)
    if roll == "A":
        score += 1
    elif roll == "B":
        score += 2
    elif roll == "C":
        score += 3
    return score

def sum_scores(data: List[Tuple[str]], rolls: dict, function) -> int:
    total_score = 0
    for game in data:
        total_score += function(game, rolls)
    return total_score





